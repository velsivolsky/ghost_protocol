const COMMAND_BY_ID = new Map(COMMAND_REGISTRY.map((item) => [item.id, item]));

export function getCommandDef(commandId) {
  return COMMAND_BY_ID.get(commandId) || null;
}

export function listCommandPhrases() {
  const values = [];

  for (const cmd of COMMAND_REGISTRY) {
    values.push(cmd.phrase);
    for (const alias of cmd.aliases) {
      values.push(alias);
    }
  }

  return values;
}
